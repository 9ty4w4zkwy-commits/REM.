import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:'chrome'});
try {
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/rem-modulare-demo.html',{waitUntil:'networkidle'});
 await page.locator('#welcomeTheme').selectOption('sepia');
 await page.locator('#welcomeStart').click();
 assert.equal(await page.locator('html').getAttribute('data-reading-theme'),'sepia','Onboarding theme should apply');
 await page.getByRole('button',{name:'Apri libro'}).first().waitFor({timeout:12000});
 const buttons=page.getByRole('button',{name:'Apri libro'});
 assert.equal(await buttons.count(),2,'Both extracted books should be available');
 assert.equal(await page.locator('.book-cover').count(),2,'Every catalog book should render a cover');
 assert.equal(await page.locator('.book-cover[data-cover-style="classic"]').count(),1,'Classic cover style comes from catalog');
 await page.locator('#bookSearch').fill('montecristo');
 assert.equal(await page.getByRole('button',{name:'Apri libro'}).count(),1,'Search should filter books');
 await page.locator('#bookSearch').fill('nessun risultato possibile');
 assert.match(await page.locator('#books').innerText(),/Nessun libro trovato/);
 await page.locator('#bookSearch').fill('');
 await buttons.first().click();
 assert.ok((await page.locator('#chapterText').innerText()).length>1000,'Casa text should be loaded');
 assert.equal(await page.locator('#chapterProgress').count(),1,'Reader should expose chapter progress');
 await page.locator('#chapterText').evaluate(el=>window.scrollTo(0,el.offsetTop+el.offsetHeight/2));
 await page.waitForTimeout(150);
 assert.ok(Number(await page.locator('#chapterProgress').evaluate(el=>el.value))>0,'Reading progress should advance on scroll');
 await page.evaluate(()=>window.scrollTo(0,0));
 const casaChapters=await page.locator('#chapter option').count();
 assert.ok(casaChapters>=2,'Casa should expose its original chapters');
 assert.equal(await page.locator('#previousChapter').isDisabled(),true,'First chapter has no previous');
 await page.locator('#nextChapter').click();
 assert.equal(await page.locator('#chapter').evaluate(el=>el.selectedIndex),1,'Next chapter button works');
 assert.equal(await page.locator('#nextChapter').isDisabled(),true,'Last chapter has no next');
 await page.locator('#previousChapter').click();
 assert.equal(await page.locator('#chapter').evaluate(el=>el.selectedIndex),0,'Previous chapter button works');
 await page.locator('#focusReading').click();
 assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('immersive-reading')),true,'Immersive mode should activate');
 assert.equal(await page.locator('#focusReading').getAttribute('aria-pressed'),'true');
 await page.locator('#focusReading').click();
 assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('immersive-reading')),false,'Immersive mode should exit');
 await page.locator('#readingNote').fill('Una nota sul primo capitolo');
 await page.locator('#chapter').selectOption({index:1});
 assert.equal(await page.locator('#readingNote').inputValue(),'','Notes must be scoped to chapter');
 const chosen=await page.locator('#chapter').inputValue();
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('#welcome').isVisible(),false,'Welcome should not repeat after completion');
 await page.getByRole('button',{name:'Apri libro'}).first().click();
 assert.equal(await page.locator('#chapter').inputValue(),chosen,'Chapter progress should survive reload');
 await page.locator('#previousChapter').click();
 assert.equal(await page.locator('#readingNote').inputValue(),'Una nota sul primo capitolo','Personal note should survive reload');
 await page.locator('#nextChapter').click();
 await page.locator('#goLibrary').click();
 assert.match(await page.locator('#historySummary').innerText(),/1 libro iniziato/);
 assert.equal(await page.locator('#resetReading').isDisabled(),false);
 assert.equal(await page.locator('.history-resume').count(),1,'One started book should be resumable');
 await page.locator('.history-resume').click();
 assert.equal(await page.locator('#chapter').inputValue(),chosen,'History resume should open saved chapter');
 await page.locator('#goLibrary').click();
 await page.getByRole('button',{name:'Apri libro'}).last().click();
 await page.locator('#chapterText').waitFor();
 assert.ok((await page.locator('#chapterText').innerText()).length>1000,'Montecristo text should be loaded');
 await page.locator('#readerAppearance').click();
 await page.locator('#fontSize').selectOption('large');
 await page.locator('#readingTheme').selectOption('night');
 assert.equal(await page.locator('html').getAttribute('data-reading-theme'),'night');
 await page.locator('#goBack').click();
 assert.equal(await page.locator('#reader').isVisible(),true,'Appearance should return to current book');
 assert.match(await page.locator('#bookTitle').innerText(),/Montecristo/);
 assert.equal(await page.locator('html').getAttribute('data-reading-theme'),'night');
 assert.equal(await page.locator('#chapterText').evaluate(el=>getComputedStyle(el).fontSize),'22.4px','Large font should apply');
 await page.locator('#minutes').selectOption('5');
 await page.locator('#timerStart').click();
 assert.match(await page.locator('#clock').innerText(),/^0[45]:[0-5][0-9]$/);
 await page.waitForTimeout(1300);
 await page.locator('#timerPause').click();
 const paused=await page.locator('#clock').innerText();
 await page.waitForTimeout(1200);
 assert.equal(await page.locator('#clock').innerText(),paused,'Focus pause should freeze clock');
 await page.locator('#timerStart').click();
 const resumed=await page.locator('#clock').innerText();
 assert.equal(resumed,paused,'Focus resume must preserve paused time');
 await page.locator('#timerReset').click();
 assert.equal(await page.locator('#clock').innerText(),'00:00');
 await page.reload({waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Apri libro'}).last().click();
 assert.ok((await page.locator('#chapterText').innerText()).length>1000,'Content should survive reload');
 assert.equal(await page.locator('html').getAttribute('data-reading-theme'),'night','Reading theme should persist after reload');
 assert.deepEqual(errors,[],'Browser JS errors');
 console.log('Chromium mobile smoke test passed');
} finally {await browser.close()}
