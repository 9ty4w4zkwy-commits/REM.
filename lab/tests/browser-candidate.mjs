import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:'chrome'});
try{
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto((process.env.REM_BASE_URL||'http://127.0.0.1:8765')+'/rem-candidata.html',{waitUntil:'networkidle'});
 assert.equal(await page.locator('#profileOnboarding').isVisible(),true,'Original profile onboarding must appear first');
 await page.getByRole('button',{name:'Iniziamo'}).click();
 assert.match(await page.locator('#profileQuestion h2').innerText(),/perdere la cognizione del tempo/);
 await page.locator('#profileSkip').click();
 assert.equal(await page.locator('#profileOnboarding').isVisible(),false,'Skipping onboarding should close it');
 assert.equal(await page.locator('#home').isVisible(),true,'Candidate should land on Home');
 assert.match(await page.locator('#homeBookTitle').innerText(),/Montecristo/);
 await page.locator('#homeLibrary').click();
 await page.getByRole('button',{name:'Apri libro'}).first().waitFor();
 assert.equal(await page.locator('.book').count(),1,'Candidate must have one book');
 assert.match(await page.locator('#books').innerText(),/Montecristo/);
 assert.doesNotMatch(await page.locator('#books').innerText(),/casa oltre il bosco/i);
 await page.getByRole('button',{name:'Apri libro'}).click();
 assert.equal(await page.locator('#bookDetail').isVisible(),true,'Candidate must open book detail before reader');
 assert.match(await page.locator('#detailTitle').innerText(),/Montecristo/);
 assert.match(await page.locator('.detail-formats').innerText(),/Non ancora disponibile/);
 await page.locator('#detailRead').click();
 assert.equal(await page.locator('#format option[value="audio"]').isDisabled(),true,'Unavailable audio must be disabled');
 assert.equal(await page.locator('#format option[value="paper"]').isDisabled(),true,'Unavailable paper synchronization must be disabled');
 assert.ok((await page.locator('#chapterText').innerText()).length>1000,'Full original Montecristo text must load');
 await page.locator('#goLibrary').click();
 await page.locator('#libraryHome').click();
 assert.equal(await page.locator('#homeResume').isVisible(),true,'Home must offer resume after reading starts');
 await page.locator('#homeResume').click();
 assert.equal(await page.locator('#reader').isVisible(),true,'Home resume must open the reader');
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('#profileOnboarding').isVisible(),false,'Skipped onboarding must not repeat');
 await page.locator('#profileEdit').click();
 assert.equal(await page.locator('#profileOnboarding').isVisible(),true,'Profile answers must be editable');
 assert.deepEqual(errors,[],'No browser JavaScript errors');
 console.log('Montecristo-only candidate smoke test passed');
}finally{await browser.close()}
